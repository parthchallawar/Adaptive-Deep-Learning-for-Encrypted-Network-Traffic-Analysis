"""Write ``src/adl_etc/dashboard/web/data.js``: the offline results the web UI's story page draws
when no service data is needed (plan phase 6, T3).

    python scripts/make_ui_data.py [--run ft-pat-ssl_tuned-d1open-s0]

Safe-Stop's and P-ECHO's closed-world accuracy-vs-mean-K fronts and the weekly drift curve come
from one run's ``results/phase4/<run>/eval/phase4.json`` and ``results/phase5/<run>/drift.json``;
the unknown-score AUROC by K is the three-seed mean from ``results/summaries/phase4_table.md``.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

OUT = Path("src/adl_etc/dashboard/web/data.js")


def thin(front: list[list[float]], max_k: float = 14.0, n: int = 45) -> list[list[float]]:
    pts = [[round(a, 3), round(b, 4)] for a, b in front if a <= max_k]
    step = max(1, len(pts) // n)
    return pts[::step] + ([pts[-1]] if pts and pts[-1] not in pts[::step] else [])


def auroc_rows(table: str, group: str) -> dict[str, dict[str, float]]:
    out: dict[str, dict[str, float]] = {}
    ks = ["1", "2", "3", "5", "8", "12", "20", "30"]
    for line in table.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 10 and cells[0] == group:
            out[cells[1]] = {
                k: float(re.match(r"[\d.]+", c).group()) for k, c in zip(ks, cells[2:], strict=True)
            }  # type: ignore[union-attr]
    return out


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--run", default="ft-pat-ssl_tuned-d1open-s0")
    args = p.parse_args(argv)
    p4 = json.loads(Path(f"results/phase4/{args.run}/eval/phase4.json").read_text())
    dr = json.loads(Path(f"results/phase5/{args.run}/drift.json").read_text())
    table = Path("results/summaries/phase4_table.md").read_text(encoding="utf-8")
    group = args.run.rsplit("-s", 1)[0]
    cw = p4["h2"]["closed_world"]
    au = auroc_rows(table, group)
    data = {
        "source": f"results/phase4 and results/phase5 for {args.run}; AUROC: 3-seed means",
        "fronts": {p: thin(cw[p]["front"]) for p in ("safe_stop", "p_echo")},
        "weeks": [
            {
                "week": w["period"][-2:],
                "split": w["split"],
                "acc": round(w["policy_accuracy"], 4),
                "f1": round(w["policy_macro_f1"], 4),
                "mean_k": round(w["policy_mean_k"], 3),
            }
            for w in dr["weeks"]
        ],
        "auroc_u": au.get("u", {}),
        "auroc_energy": au.get("energy_raw", {}),
    }
    OUT.write_text(
        "// Generated by scripts/make_ui_data.py: offline results the story page draws.\n"
        f"window.ANYTIME_DATA = {json.dumps(data)};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
